--[[ ==========================================================================
  SpellUnlocker 配置文件  （霍格沃茨之遗 / UE4SS Lua Mod）  v1.5.0
  --------------------------------------------------------------------------
  改这个文件即可「选择性」开启功能。改完：
    * 游戏内按 Ctrl+R（UE4SS 热重载）立即生效，或
    * 重启游戏生效。

  提示：本文件是 Lua 语法，true / false 必须小写；每行末尾不要漏掉逗号。
========================================================================== ]]

return {

    -- 总开关：false = 整个 Mod 不做事（但已加载）
    Enabled = true,

    Features = {

        ---------------------------------------------------------------
        -- 1) 解锁全部咒语：所有咒语直接可用，不需要上课 / 任务 / 知识卡
        --    做法：挂钩游戏自己的解锁判定 IsUnlocked()，让它永远返回 true
        --    已实测：全部咒语可选（玩家游戏内确认）
        UnlockAllSpells = true,

        ---------------------------------------------------------------
        -- 2) 一键补满知识卡（CompleteAllKnowledgeCards）
        --    副作用较大：会连带解锁图鉴/挑战/部分剧情门禁，且会写存档
        --    建议：先只开 1)，只有在 1) 不够用时再开这个
        CompleteKnowledge = false,

        ---------------------------------------------------------------
        -- 3) 冷却归零（安全模式）
        --    做法：① SetCooldownRateScale(CooldownRateScale) 让冷却高速恢复
        --          ② 挂钩 GetCooldownPercent / ByName 让 UI/判定读到 0
        ZeroCooldown = true,

        ---------------------------------------------------------------
        -- 4) 强制可施放（★ 冷却不再阻挡的关键项）
        --    做法：① WandTool::IsSpellToolAvailable 恒返回 true
        --          ② ActivateSpellTool 的 bImmediate 改成 true（立即施法）
        --    已实测：同一咒语可以连放，不再等冷却
        ForceSpellAvailable = true,

        ---------------------------------------------------------------
        -- 5) 扩展法术槽位：每个法组 4 槽 → SlotsPerLoadout 个
        --    副作用：UI 只画 4 个槽，扩了可能显示异常。默认关闭
        ExpandSpellSlots = false,

        ---------------------------------------------------------------
        -- 6) 天赋全开：调用 PerksTree 的 Exec 接口激活全部天赋并补天赋点
        --    副作用：会写存档
        UnlockAllPerks = false,

    },

    ---------------------------------------------------------------
    -- 参数
    ---------------------------------------------------------------

    -- 冷却恢复速率倍率（1 = 原版，1000 = 冷却几乎瞬间恢复）
    CooldownRateScale = 1000.0,

    -- 扩展槽位时的每法组咒语数（实验性，配合 ExpandSpellSlots）
    SlotsPerLoadout = 8,

    -- 法组数量（游戏默认 CDO 是 3，别乱改）
    NumLoadouts = 3,

    -- 启动后延迟多久开始应用（毫秒）
    ApplyDelayMs = 1500,

    -- 是否输出诊断信息（hook 命中数 / 咒语数量等，只读整数，安全）
    -- 只在"第一次应用"时输出
    ProbeDump = true,

    -- ★ 危险（默认关）：把咒语 FName 转成字符串打印。
    --   本游戏版本上 UE4SS 的 FName 转换会抛 C++ 异常（pcall 拦不住），
    --   v1.4 的崩溃就是它造成的，除非你在排查问题，否则保持 false。
    DumpSpellNames = false,

    -- 快捷键：切换总开关。可填 "F1".."F12"，"" 表示不用
    ToggleHotkey = "F8",

    -- 施法时把 bImmediate 参数改成 true（配合 ForceSpellAvailable 用）
    -- 若你关掉 ForceSpellAvailable，这一项也就没有意义了
    ImmediateCast = true,

    ---------------------------------------------------------------
    -- ★ 危险开关（默认关闭，除非确有必要不要打开）
    --    这两个在本游戏版本上曾导致 UE Fatal Error / 崩溃
    ---------------------------------------------------------------

    -- 逐咒语调 AdjustCooldown 清冷却（会逐条打印 call i/n，崩溃时可定位）
    HardClearCooldowns = false,

    -- 按分类调 AdjustCooldownsByCategory 清冷却
    ClearCooldownsByCategory = false,
}
